//
// RAX happened to still hold the phi *source* from the forward edge's
// `mov edx,eax`, so the first iteration tested the right value. The latch
// incremented RDX and jumped back past that copy, leaving RAX at 0 forever:
//
//   mov  edx,ecx     ; i + 1, into the counter's register
//   jmp  <header>    ; lands after the copy that set RAX
//   cmp  eax,0x5     ; still 0
//
// The fix is that cheapness is not recomputability: choose_split_kind now asks
// Op::is_rematerializable, which admits only Iconst, Fconst, StackAddr and
// GlobalAddr. BlockParam, Param, CallResult and LoadResult are all leaves of
// cost ~0 and all name a value that exists at exactly one program point.
//
