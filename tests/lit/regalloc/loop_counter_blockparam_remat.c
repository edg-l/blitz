// Regression test: a `for (i = 0; i < 5; i++)` loop that never terminated.
//
// The splitter rematerialized a `BlockParam` pseudo-op. A BlockParam computes
// nothing -- it declares that the value is already in its register when the
// block starts, put there by a predecessor's phi copy -- so re-emitting it mints
// a VReg that no instruction ever writes, and the allocator hands it a register
